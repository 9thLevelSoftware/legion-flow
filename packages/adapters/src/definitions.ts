import type { EgressRoute } from "@9thlevelsoftware/legion-flow-schema";
import type { CapabilityProfile } from "@9thlevelsoftware/legion-flow-engine";

/** The vendor CLI versions baked into the agent image. Bumping one changes the image tag, so a run records which it used. */
export const AGENT_CLI_VERSIONS = { claude: "2.1.295", codex: "0.162.0" } as const;

/** glibc base: the codex npm package ships no musl build, so node:22-alpine cannot host it. */
export const AGENT_BASE_IMAGE = "node:22-bookworm-slim";

export function agentImageTag(versions = AGENT_CLI_VERSIONS): string {
  return `legion-flow-agent:claude-${versions.claude}-codex-${versions.codex}`;
}

/** The Dockerfile the sandbox writes and the FIX line names. Never built implicitly. */
export function agentDockerfile(versions = AGENT_CLI_VERSIONS): string {
  return [
    "# Generated by legion-flow. The agent image: a pinned node base plus the vendor CLIs at pinned versions.",
    "# Build it deliberately with the command legion-flow prints; execute never builds or pulls on its own.",
    `FROM ${AGENT_BASE_IMAGE}`,
    `RUN npm install -g @anthropic-ai/claude-code@${versions.claude} @openai/codex@${versions.codex} && npm cache clean --force`,
    "# uid 1000 is `node` in the base image; the run mounts a tmpfs at /home/node so a read-only root still has a writable home.",
    "USER 1000:1000",
    "ENV HOME=/home/node",
    "",
  ].join("\n");
}

export interface VendorPrefix {
  match: "contains" | "startsWith";
  text: string;
}

/** Everything doctor and execute need to know about a real adapter without running it. */
export interface AdapterDefinition {
  id: "claude" | "codex";
  binary: string;
  vendorPrefix: VendorPrefix;
  profile: CapabilityProfile;
  credentialEnv: string;
  baseUrlEnv: string;
  route: EgressRoute;
  /** Declared constants set inside the container (safe to record). */
  containerEnv: Record<string, string>;
  installHint: string;
  /**
   * Set when a provider replaces the vendor's own API (M4 slice y). `agentCredentialEnv` is the variable the CLI
   * reads (the placeholder in a container, the real value on the host), `hostBaseUrl` the API root the host tier
   * points the CLI at, and `modelEnv` the CLI's model variables. Cost is then unknown: the CLI prices at its vendor's rates.
   */
  provider?: { baseUrl: string; agentCredentialEnv: string; hostBaseUrl: string; modelEnv: Record<string, string>; codexCatalog?: Record<string, unknown> };
}

/** `project.json` `adapter.http` once it names a provider. */
export interface AdapterProvider {
  baseUrl: string;
  apiKeyEnv: string;
  model?: string;
  contextWindow?: number;
}

/** codex's model catalog file is codex-internal; these field names were found against codex-cli 0.162.0 (M4 slice aa). */
export const CODEX_DEFAULT_CONTEXT_WINDOW = 128_000;

/**
 * One catalog entry for a provider's model, with values true of a plain Responses provider: "Responses lite" and the
 * freeform patch tool (as MiMo's own codex guide requires), no experimental tools, no verbosity, three reasoning
 * levels, and a one-line base instruction Legion wrote (the brief carries the task), never codex's built-in text.
 */
export function codexCatalog(model: string, contextWindow = CODEX_DEFAULT_CONTEXT_WINDOW): Record<string, unknown> {
  return {
    models: [
      {
        slug: model,
        display_name: model,
        base_instructions: "You are a coding agent running non-interactively. Follow the user message exactly. Use the provided tools to read and edit files, and report what you changed.",
        use_responses_lite: true,
        apply_patch_tool_type: "freeform",
        context_window: contextWindow,
        supported_reasoning_levels: [
          { effort: "low", description: "Fast responses with lighter reasoning" },
          { effort: "medium", description: "Balances speed and reasoning depth" },
          { effort: "high", description: "Greater reasoning depth" },
        ],
        shell_type: "shell_command",
        visibility: "list",
        supported_in_api: true,
        priority: 1,
        support_verbosity: false,
        truncation_policy: { mode: "tokens", limit: 10_000 },
        experimental_supported_tools: [],
      },
    ],
  };
}

/**
 * The claude definition pointed at an Anthropic-compatible provider (M4 slice y): the route goes to the provider's
 * host under its path with the key as a bearer token set by the proxy, the credential is the provider's variable,
 * and the CLI reads the placeholder (or, on the host, the real value) as ANTHROPIC_AUTH_TOKEN, never ANTHROPIC_API_KEY,
 * so exactly one auth header leaves the agent and it is the one the proxy overwrites.
 */
export function withProvider(def: AdapterDefinition, provider: AdapterProvider): AdapterDefinition {
  if (def.id === "codex" && !provider.model) throw new Error("adapter_provider_model_required: codex with a provider needs adapter.http.model; its model catalog is keyed by it");
  const u = new URL(provider.baseUrl);
  const basePath = u.pathname.replace(/\/+$/, "");
  const scheme = u.protocol === "http:" ? "http" : "https";
  const modelEnv: Record<string, string> = provider.model && def.id === "claude"
    ? { ANTHROPIC_MODEL: provider.model, ANTHROPIC_DEFAULT_OPUS_MODEL: provider.model, ANTHROPIC_DEFAULT_SONNET_MODEL: provider.model, ANTHROPIC_DEFAULT_HAIKU_MODEL: provider.model }
    : {};
  return {
    ...def,
    profile: { ...def.profile, reportsUsage: { ...def.profile.reportsUsage, cost: false } },
    credentialEnv: provider.apiKeyEnv,
    route: {
      alias: def.route.alias,
      host: u.hostname.replace(/^\[|\]$/g, ""),
      ...(u.port ? { port: Number(u.port) } : {}),
      scheme,
      ...(basePath ? { basePath } : {}),
      secrets: [{ header: "authorization", ref: `env:${provider.apiKeyEnv}`, prefix: "Bearer " }],
    },
    // claude reads a bearer token from ANTHROPIC_AUTH_TOKEN; codex's provider reads OPENAI_API_KEY (its env_key) and sends it as a bearer token.
    provider: { baseUrl: provider.baseUrl, agentCredentialEnv: def.id === "claude" ? "ANTHROPIC_AUTH_TOKEN" : "OPENAI_API_KEY", hostBaseUrl: provider.baseUrl.replace(/\/+$/, ""), modelEnv, ...(def.id === "codex" ? { codexCatalog: codexCatalog(provider.model!, provider.contextWindow) } : {}) },
  };
}

