export const ADAPTER_DEFINITIONS: readonly AdapterDefinition[] = [CLAUDE_DEFINITION, CODEX_DEFINITION];

export function adapterDefinition(id: string): AdapterDefinition | null {
  return ADAPTER_DEFINITIONS.find((d) => d.id === id) ?? null;
}

export function vendorPrefixMatches(prefix: VendorPrefix, versionOutput: string): boolean {
  const text = versionOutput.trim();
  return prefix.match === "contains" ? text.includes(prefix.text) : text.startsWith(prefix.text);
}
